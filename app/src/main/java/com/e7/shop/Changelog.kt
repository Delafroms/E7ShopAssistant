## V1 正式版

这个版本不是把版本号从 0.x 改成 1.0，而是经过一轮完整的工程重建之后，
第一次可以作为正式版本交付。

### 识图体系：双引擎

- **YOLO 视觉识别** 与 **传统识图** 是地位平等的两套完整识别引擎，
  通过统一的识别接口输出同一结构的结果；识别只负责"看见什么"，
  决策与操作完全独立——以后接入第三种引擎，不需要改动任何业务逻辑。
- **传统识图引擎重新设计**：由购买按钮位置推导行结构、图标区颜色签名、
  文本校验，每个候选都携带可解释的证据链；每帧固定一次 OCR，
  不依赖视觉模型，低配置设备也能稳定使用。
- YOLO 模型不可用时自动改用传统识图，并在界面明确提示。
- 持续提升目标识别准确率与召回率，并通过识别、决策、操作分层
  降低异常操作风险。

### 稳定性（真机日志逐一定位修复）

- 修复 YOLO 引擎启动即崩溃（输出转置越界）。
- 修复"引擎已启动、画面明明是商店、却完全不动"的根因：
