- 修复目标出现瞬间崩溃（检测候选容器扩容问题）。
- 修复界面与引擎状态失步（引擎在跑、界面却显示未运行）。
- 中断恢复：任何时刻重新点「开始」，都会结束上一轮任务、清空本轮统计、
  从当前画面重新识别并自动恢复，残留弹窗会被安全关闭。

### 界面

