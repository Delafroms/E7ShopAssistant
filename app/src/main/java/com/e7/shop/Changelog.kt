## V1 正式版

这个版本不是把版本号从 0.x 改成 1.0，而是经过一轮完整的工程重建之后，
第一次可以作为正式版本交付。

### 识图体系：双引擎

- **YOLO 视觉识别** 与 **传统识图** 是地位平等的两套完整识别引擎，
  通过统一的识别接口输出同一结构的结果；识别只负责"看见什么"，
  决策与操作完全独立——以后接入第三种引擎，不需要改动任何业务逻辑。
- **传统识图引擎重新设计**：由购买按钮位置推导行结构、图标区颜色签名、
  文本校验，每个候选都携带可解释的证据链；每帧固定一次 OCR，
  不依赖视觉模型，低配置设备也能稳定使用。
- YOLO 模型不可用时自动改用传统识图，并在界面明确提示。
- 持续提升目标识别准确率与召回率，并通过识别、决策、操作分层
  降低异常操作风险。

### 稳定性（真机日志逐一定位修复）

- 修复 YOLO 引擎启动即崩溃（输出转置越界）。
- 修复"引擎已启动、画面明明是商店、却完全不动"的根因：
  底层并行调度空实现导致图像缩放输出全零——识别全链路无效。
- 修复目标出现瞬间崩溃（检测候选容器扩容问题）。
- 修复界面与引擎状态失步（引擎在跑、界面却显示未运行）。
- 中断恢复：任何时刻重新点「开始」，都会结束上一轮任务、清空本轮统计、
  从当前画面重新识别并自动恢复，残留弹窗会被安全关闭。

### 界面

- **主题系统"换房子"**：切换主题 = 进入另一套完整设计的界面，
  不只是换颜色。内置三套，各有独立的设计语言：
  - Steam · 深色卡片（Steam 客户端控制台：深蓝头图、品牌蓝高亮、
    绿色 PLAY 运行键、大写分区标题）
  - Steam · OLED 纯黑（Steam 结构的纯黑变体：平面色块、无渐变，
    AMOLED 友好）
  - Blue Archive · 明亮学院（完全不同的布局结构：网点半调、横幅、
    相框卡片、旋转仪表盘、底部操作条、BA 光环徽章与角色素材位）
- **悬浮窗彻底重建为"任务面板"**：旧悬浮窗的胶囊 + 六格统计面板
  被推倒重做。新结构 = 状态胶囊（状态点 / 阶段 / 运行时长 / 引擎徽标 /
  错误行）+ 展开任务面板（任务横幅、引擎与截图健康、2×3 统计、
  滚动事件日志、双行控制区）；展开收起动画、右缘锚定宽度切换、
  拖拽与刘海安全区自适应。悬浮窗随主题切换整套结构
  （Steam 控制台 / OLED 极简 / BA 学园），不是换色。
- **点击逻辑双模式**：传统点击（录制/预设动作方案，稳定兼容）与 AI 点击（推荐）
  是两套完全独立的管线。AI 点击 = YOLO 实时识别（眼睛）+ 独立决策状态机
  （观察 → 判断 → 点击闭环）+ 无障碍执行（手）；通过按钮色块判断可点击状态
  （金/蓝等彩色可点 / 灰色售空），无法确定时明确报告，绝不回退传统点击。
- **更新日志阅读体验**：全屏阅读、主题感知配色、更大字号与行距、
  版本层级配色、连续列表排版。
- **完整中英文**：界面、对话框、按钮、状态、错误、悬浮窗全部双语，
  切换即时生效、重启保持。
- 设置系统收敛为统一配置模型：任何主题下的设置功能完全一致，
  换主题只换呈现、不删功能。

