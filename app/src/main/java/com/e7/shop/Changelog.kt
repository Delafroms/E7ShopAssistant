## V1 修复更新

这一轮针对"漏买 / 误买"与"预算失控"做了系统性加固，并把排查能力补齐。
改动均经真机装机与识别回归台验证（89 张样本，召回 100%、误检 1）。

### 预算：修掉一个会无限消耗付费货币的缺陷

- **AI 点击模式下，刷新确认一旦点下就立即记账。** 此前是"等画面验证通过才记账"，
  而验证在三种常见情况下都不会通过（刷新前后画面相同、行数不足、网络超时）——
  于是天空石花掉了却不计数，**预算上限永远不会触发，可以整夜无限刷新**。
  传统点击模式此前已修复，这次把 AI 模式对齐。
- **购买确认同样改为"点下即记账"**，金币消耗上限不会再被超出。
- 「金币消耗上限」补了使用说明：**建议设为当前金币余额减 30 万以上，
  且每轮挂机前按当时余额重设**（该上限是每轮独立计算的自我记账，
  不是对游戏内余额的监控）。

### 漏买：点击没生效，不再被当成"这行处理完了"

- AI 模式下，若点完购买按钮但弹窗没出现、**按钮仍显示可购买**，
  说明这一次点击没有生效（坐标偏了 / 被系统对话框挡住）。
  旧逻辑会把这一行标记为"已处理"，从而**整屏漏买**；
  现在改为保持未决、下一轮重新决策（绝不拿旧帧的坐标去点）。

### 误买：不再把"没买到"记成"买到了"

- 购买结果的判据从"弹窗消失了就算成功"改为**要求正向证据：画面回到商店列表**。
  旧判据会把**任何**非购买弹窗都当成"弹窗关掉了"——金币不足时的错误提示窗
  恰好符合，于是日志写下一条假的"买到了"、统计里多算一件（假阳性）。
  现在失败会记为 `PURCHASE FAILED` 并附上弹窗原文，计数不再虚高。
- 超时无法确认时仍按"可能已买到"保守计数，但日志明确标注 `UNCONFIRMED`。

### 稳定性

- 修复"机器人运行中打开装备评分页会闪退"（原生模型被重复加载并释放）。
- 修复"模型文件损坏时仍提示加载成功"——现在会明确报告失败并回退传统识图。
- 修复选大图做背景 / 自定义 Logo 时可能闪退（改为按屏幕尺寸采样解码）。
- 修复 Blue Archive 主题下点「开始」毫无反应（缺少风险确认闸门）。
- 修复"手动停止被记录成崩溃"，日志不再误报异常。
- 新增崩溃日志：主循环之外的意外崩溃会写入 `e7sa_crash.log`，便于事后排查。
- 修复 Shizuku「一键开启无障碍」通道（缺少必要声明，此前点了必然失败）。

### 日志与排查

- **AI 点击模式补上滑动日志**：每次滑动记录次数、画面是否移动、识别到几个目标、
  睡眠模式开关状态，以及"凭什么判定已滑到底"。
- **新增记账时刻日志**（`REFRESH COMMIT` / `PURCHASE COMMIT`）：
  钱花出去的那一刻就留下记录、与验证结果无关，可直接对账。
- 「无障碍保活豁免」改为设置项里的可见开关（此前是静默修改系统设置）。

